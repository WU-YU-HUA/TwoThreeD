/** Explicit draft export preserves pending review state; validated is the default. */
export function export3D(scene, { format = 'dae',mode='validated',filename='twothreeD',container='zip',labelTextures=new Map(),createdAt } = {}) {
  const extension = String(format).toLowerCase().replace(/^\./, '');
  let code, message;
  if (!scene || scene.schema !== 'Scene3D') {
    code = 'E_SCENE_REQUIRED'; message = '輸出需要正式 Scene3D，不能使用規劃 JSON 或未辨識的 2D 資料。';
  } else if (scene.extensions?.twothreeD?.preview_only&&mode!=='draft') {
    code = 'E_PREVIEW_ONLY'; message = '這是待核對的預覽初稿，不能當成正式模型匯出。';
  } else if (scene.schema_version !== '1.0.0' || scene.units !== 'mm') {
    code = 'E_SCHEMA_VERSION'; message = '輸出介面需要毫米制 Scene3D@1.0.0。';
  } else if (extension !== 'dae') {
    code = 'E_UNSUPPORTED_OUTPUT'; message = `尚未支援 ${extension} 輸出格式。`;
  } else if(!['validated','draft'].includes(mode)||!['dae','zip'].includes(container)) {
    code='E_EXPORT_OPTIONS';message='匯出模式無效。';
  } else {
    try{
      const draft=mode==='draft',result=serializeDae(scene,{labelTextures,draft,...(createdAt?{createdAt}:{})});
      if(container==='dae'&&result.files.length){const error=new Error('模型仍有外部貼圖，需使用 ZIP 保留全部檔案。');error.code='E_EXTERNAL_RESOURCES';throw error;}
      const source=scene.extensions?.twothreeD?.source_filename||'Scene3D',credits=scene.extensions?.twothreeD?.model_sources||[];
      const readme=[
        'twothreeD - SketchUp editable '+(draft?'DRAFT':'model'),
        '', '使用方式（SketchUp 桌面版，目標版本 2025）',
        '1. 將整個 ZIP 解壓縮；model.dae 與 textures 資料夾保持相鄰。',
        '2. SketchUp：檔案 → 匯入 → COLLADA (*.dae)，選擇 model.dae。',
        '3. 保留「驗證 COLLADA 檔案」；可開啟「合併共平面」以簡化三角形邊。',
        '4. 匯入後使用縮放至全圖。若外面有總群組，雙擊進入後再選取個別牆、櫃體、設備。',
        '5. 刪除／替換物件後，另存為 SketchUp (.skp)。',
        '', `來源：${source}`,`單位：毫米；Z 向上。${result.summary.groups} 個群組、${result.summary.meshes} 個網格、${result.summary.label_textures} 張標籤貼圖。`,
        '各物件與零件保留 node 階層；幾何已是世界座標，沒有重複比例或樓層位移。',
        '多邊形轉為三角形，保留凹角與孔洞。材質為目前預覽的純色及標籤貼圖。',
        result.summary.label_textures?'標名方塊文字為 PNG 貼圖；物件可獨立選取刪除。':'缺少模型時顯示無字紅色方塊；可獨立選取刪除，名稱保留在群組中。',
        '不含原始 PDF、DXF 或面向使用者的 JSON 檔。',
        '',draft?'此檔為可編輯初稿：比例與辨識尚待核對，保留原始未確認狀態。':'此檔為 Scene3D 匯出結果。',
        '門框、窗、地板及其他尚未辨識的構件不會憑空補上；素材不是精確產品規格。',
        '未保留來源動畫、PBR 金屬度／粗糙度或平滑法線；不是參數化／動態 SketchUp 元件。',
        '尚未在 Windows SketchUp 2025 實測群組編輯、尺寸與另存重開；格式驗證不等於實機驗收。',
        '官方匯入說明：https://help.sketchup.com/en/sketchup/importing-and-exporting-collada-files',
        '', '模型作者、來源與授權見 CREDITS.txt。',''
      ].join('\n');
      const creditText=['Model sources / 模型引用', 'External assets are CC0-1.0; source credits retained.',
        'Runtime geometry is scaled/placed from the drawing, with base colors and zero-area triangles removed.',
        ...credits.map(c=>`${c.citation||c.id}\nSource: ${c.source_url||''}\nLicense: ${c.license||''}\nSource SHA-256: ${c.sha256||''}`),
        'Built-in walls, furniture templates and label images: generated by twothreeD.',''].join('\n\n');
      const files=[{path:'model.dae',content:result.document},...result.files,{path:'README.txt',content:readme},{path:'CREDITS.txt',content:creditText}];
      const stem=String(filename).replace(/\.[^.]+$/,'').replace(/[<>:"/\\|?*\u0000-\u001f]/g,'_').slice(0,100).trim()||'twothreeD';
      const artifact=container==='dae'?{filename:stem+(draft?'-editable-draft':'')+'.dae',mimeType:'model/vnd.collada+xml',content:new TextEncoder().encode(result.document)}:{filename:stem+(draft?'-editable-draft':'')+'.zip',mimeType:'application/zip',content:zipFiles(files)};
      return {success:true,artifact,files:container==='dae'?[{path:artifact.filename,content:result.document}]:files,summary:result.summary,diagnostics:[...(draft?[{severity:'warning',code:'W_DRAFT_EXPORT',message:'已輸出待核對的可編輯初稿，未將辨識結果改成已確認。'}]:[]),{severity:'warning',code:'W_SKETCHUP_UNVERIFIED',message:'格式與資料已驗證；SketchUp 2025 實機匯入與編輯仍待驗收。'}]};
    }catch(error){code=error.code||'E_EXPORT_FAILED';message=error.message;}
  }
  return { success: false, artifact: null, diagnostics: [{ severity: 'error', code, message }] };
}

/** Inspection artifact, not a downloadable CAD/3D model. Browser-independent. */
export function createJsonArtifact(filename, data) {
  if (!/^[^/\\]+\.json$/i.test(filename)) throw new Error('JSON 輸出請提供不含路徑的 .json 檔名。');
  return { filename, mimeType: 'application/json;charset=utf-8', content: pretty(data) + '\n' };
}

function pretty(value, depth = 0) {
  const pad = '  '.repeat(depth), next = pad + '  ';
  if (value === null || typeof value !== 'object') {
    if (value === undefined || (typeof value === 'number' && !Number.isFinite(value))) throw new Error('JSON 含有無效值。');
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    if (value.every(item => item === null || typeof item !== 'object')) return '[' + value.map(item => pretty(item)).join(',') + ']';
    return '[\n' + value.map(item => next + pretty(item, depth + 1)).join(',\n') + '\n' + pad + ']';
  }
  const entries = Object.entries(value);
  if (!entries.length) return '{}';
  return '{\n' + entries.map(([key, item]) => next + JSON.stringify(key) + ': ' + pretty(item, depth + 1)).join(',\n') + '\n' + pad + '}';
}
